"""Real PostgreSQL checks, enabled only with an explicit test connection URL.

Each test creates and removes a unique private test schema. Never uses public
or the application's vetinsight schema, and never reads production rows.
"""
import importlib
import os
from pathlib import Path
import tempfile
import unittest
from uuid import uuid4

from fastapi.testclient import TestClient
import psycopg
from psycopg import sql

from tests.auth_helpers import bootstrap, sign_in, PASSWORD
from tests.test_annotations import image_bytes


@unittest.skipUnless(os.environ.get('VETINSIGHT_TEST_DATABASE_URL'), 'Explicit PostgreSQL test connection is not configured')
class PostgresTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.schema = 'vetinsight_test_' + uuid4().hex[:16]
        self.previous = {key: os.environ.get(key) for key in ('VETINSIGHT_DATA_DIR', 'VETINSIGHT_DATABASE_URL', 'VETINSIGHT_DATABASE_SCHEMA', 'VETINSIGHT_STORAGE_PROVIDER')}
        os.environ.update(VETINSIGHT_DATA_DIR=self.temp.name,
                          VETINSIGHT_DATABASE_URL=os.environ['VETINSIGHT_TEST_DATABASE_URL'],
                          VETINSIGHT_DATABASE_SCHEMA=self.schema, VETINSIGHT_STORAGE_PROVIDER='local')
        from app import main
        self.main = importlib.reload(main)
        self.client = TestClient(self.main.app)
        self.client.__enter__()
        bootstrap(self.main); sign_in(self.client)

    def tearDown(self):
        self.client.__exit__(None, None, None)
        # The schema name is generated by this test, not supplied by configuration.
        assert self.schema.startswith('vetinsight_test_')
        with psycopg.connect(os.environ['VETINSIGHT_TEST_DATABASE_URL'], autocommit=True) as db:
            db.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(self.schema)))
        for key, previous in self.previous.items():
            if previous is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = previous
        self.temp.cleanup()

    def test_case_upload_review_split_and_export_contract(self):
        response = self.client.post('/cases', json={'patient_name': 'PG fixture', 'species': 'Test'})
        self.assertEqual(response.status_code, 201, response.text)
        case_id = response.json()['id']
        self.assertEqual(len(self.client.get('/cases?search=pg').json()), 1)
        content = image_bytes()
        info = self.client.post(f'/cases/{case_id}/uploads', files={'file': ('shape.png', content, 'image/png')}).json()
        self.assertEqual(self.client.get(info['download_url']).content, content)
        payload = {'revision': 0, 'review_status': 'Reviewed', 'annotations': [
            {'id': str(uuid4()), 'x': .1, 'y': .2, 'width': .3, 'height': .4, 'category': 'Geometry', 'review_status': 'Reviewed', 'notes': ''}]}
        path = f'/cases/{case_id}/uploads/{info["id"]}/annotations'
        self.assertEqual(self.client.put(path, json=payload).status_code, 200)
        self.assertEqual(self.client.put(path, json=payload).status_code, 409)
        self.assertEqual(self.client.put(f'/cases/{case_id}/dataset-assignment', json={'split': 'train', 'revision': 0}).status_code, 200)
        self.assertEqual(self.client.get(f'/cases/{case_id}/exports/coco').status_code, 200)
        dashboard = self.client.get('/dashboard').json()
        self.assertEqual((dashboard['case_count'], dashboard['image_count'], dashboard['annotation_count']), (1, 1, 1))

    def test_admin_update_duplicate_and_schema_access(self):
        response = self.client.post('/admin/users', json={'username': 'pg-member', 'display_name': 'PG member', 'password': PASSWORD})
        self.assertEqual(response.status_code, 201, response.text)
        user_id = response.json()['id']
        self.assertEqual(self.client.post('/admin/users', json={'username': 'PG-MEMBER', 'display_name': 'Duplicate', 'password': PASSWORD}).status_code, 409)
        response = self.client.put(f'/admin/users/{user_id}', json={'display_name': 'Updated', 'role': 'member', 'active': False})
        self.assertEqual(response.status_code, 200, response.text)
        self.assertFalse(response.json()['active'])
        self.assertEqual(self.client.put('/admin/users/1', json={'display_name': 'Admin', 'role': 'member', 'active': True}).status_code, 409)
        with self.main.database() as db:
            secured = db.raw.execute('SELECT relrowsecurity FROM pg_class JOIN pg_namespace n ON n.oid=relnamespace WHERE n.nspname=%s AND relkind=%s', (self.schema, 'r')).fetchall()
            self.assertTrue(secured)
            self.assertTrue(all(row['relrowsecurity'] for row in secured))
            if db.raw.execute("SELECT 1 FROM pg_roles WHERE rolname='anon'").fetchone():
                permission = db.raw.execute("SELECT has_schema_privilege('anon',%s,'USAGE') AS allowed", (self.schema,)).fetchone()
                self.assertFalse(permission['allowed'])
