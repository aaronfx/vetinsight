"""The existing SQL contract on SQLite and a private PostgreSQL schema."""
from collections.abc import Mapping
from contextlib import contextmanager
import re
import sqlite3

import psycopg
from psycopg.rows import dict_row

TABLES = ('cases', 'uploads', 'annotation_sets', 'dataset_assignments', 'users', 'sessions', 'audit_events', 'login_limits', 'analysis_runs')


class DatabaseError(Exception):
    pass


class IntegrityError(DatabaseError):
    pass


class Record(Mapping):
    def __init__(self, values):
        self.values = values

    def __getitem__(self, key):
        return tuple(self.values.values())[key] if isinstance(key, int) else self.values[key]

    def __iter__(self):
        return iter(self.values)

    def __len__(self):
        return len(self.values)


def postgres_sql(sql):
    """Convert bind markers, never bound values or question marks in literals."""
    result, quoted, index = [], False, 0
    while index < len(sql):
        char = sql[index]
        if char == "'":
            if quoted and index + 1 < len(sql) and sql[index + 1] == "'":
                result.extend(["'", "'"]); index += 2; continue
            quoted = not quoted
        result.append('%s' if char == '?' and not quoted else '%%' if char == '%' else char)
        index += 1
    return ''.join(result)


class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor, self.lastrowid = cursor, lastrowid

    def fetchone(self):
        value = self.cursor.fetchone()
        return Record(value) if isinstance(value, dict) else value

    def fetchall(self):
        return [Record(value) if isinstance(value, dict) else value for value in self.cursor.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


class Connection:
    def __init__(self, raw, postgres=False, schema='vetinsight'):
        self.raw, self.postgres, self.schema = raw, postgres, schema

    def execute(self, sql, parameters=()):
        try:
            if not self.postgres:
                return self.raw.execute(sql, parameters)
            if sql.strip().upper() == 'BEGIN IMMEDIATE':
                self.raw.execute('BEGIN')
                # Preserve SQLite's serialized write decisions for revision and last-admin checks.
                return Cursor(self.raw.execute('SELECT pg_advisory_xact_lock(871403221)'))
            if sql.strip().upper() == 'BEGIN':
                return Cursor(self.raw.execute('BEGIN ISOLATION LEVEL REPEATABLE READ'))
            returning = re.match(r'\s*INSERT\s+INTO\s+(cases|uploads|users)\s*\(', sql, re.I) and 'RETURNING' not in sql.upper()
            query = postgres_sql(sql)
            if returning:
                query += ' RETURNING id'
            cursor = self.raw.execute(query, tuple(int(value) if isinstance(value, bool) else value for value in parameters))
            return Cursor(cursor, cursor.fetchone()['id'] if returning else None)
        except (sqlite3.IntegrityError, psycopg.IntegrityError):
            raise IntegrityError('Database integrity constraint failed.') from None
        except (sqlite3.Error, psycopg.Error):
            raise DatabaseError('Database operation failed.') from None

    def executescript(self, sql):
        try:
            if not self.postgres:
                return self.raw.executescript(sql)
            self.raw.execute(f'CREATE SCHEMA IF NOT EXISTS {self.schema}')
            sql = sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            sql = sql.replace('COLLATE NOCASE', '').replace('expires_at REAL', 'expires_at DOUBLE PRECISION').replace('started_at REAL', 'started_at DOUBLE PRECISION')
            sql = re.sub(r'(\w+_id) INTEGER', r'\1 BIGINT', sql)
            sql = sql.replace('size_bytes INTEGER', 'size_bytes BIGINT')
            for statement in sql.split(';'):
                if statement.strip():
                    self.raw.execute(statement)
        except psycopg.Error:
            raise DatabaseError('Database schema initialization failed.') from None

    def protect_schema(self):
        if self.postgres:
            self.raw.execute(f'REVOKE ALL ON SCHEMA {self.schema} FROM PUBLIC')
            self.raw.execute(f'CREATE UNIQUE INDEX IF NOT EXISTS usernames_casefold ON {self.schema}.users (LOWER(username))')
            for table in TABLES:
                self.raw.execute(f'ALTER TABLE {self.schema}.{table} ENABLE ROW LEVEL SECURITY')
                self.raw.execute(f'REVOKE ALL ON {self.schema}.{table} FROM PUBLIC')
            for role in ('anon', 'authenticated'):
                if self.raw.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone():
                    self.raw.execute(f'REVOKE ALL ON SCHEMA {self.schema} FROM {role}')
                    self.raw.execute(f'REVOKE ALL ON ALL TABLES IN SCHEMA {self.schema} FROM {role}')


@contextmanager
def connect(data_dir, database_url='', schema='vetinsight'):
    if not re.fullmatch(r'vetinsight(?:_[a-z0-9_]{1,40})?', schema):
        raise ValueError('Invalid private database schema.')
    try:
        if database_url:
            raw = psycopg.connect(database_url, connect_timeout=10, autocommit=True, row_factory=dict_row,
                                  application_name='vetinsight', prepare_threshold=None)
            raw.execute(f'SET search_path TO {schema}, pg_catalog')
            raw.autocommit = False
        else:
            raw = sqlite3.connect(data_dir / 'vetinsight.sqlite3', timeout=10)
            raw.row_factory = sqlite3.Row
            raw.execute('PRAGMA foreign_keys = ON')
    except (sqlite3.Error, psycopg.Error):
        raise DatabaseError('Database connection is unavailable.') from None
    try:
        with raw:
            yield Connection(raw, bool(database_url), schema)
    except psycopg.Error:
        raise DatabaseError('Database transaction failed.') from None
    finally:
        raw.close()
